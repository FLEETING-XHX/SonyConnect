"""Decode the user-provided Penpot path buffer into SVG and native geometry."""
import base64
import json
from pathlib import Path
import struct

root = Path(__file__).resolve().parents[1]
source = root / "native/resources/branding/battery-penpot.json"
data = json.loads(source.read_text(encoding="utf-8"))
raw = base64.b64decode(data["pathData"], validate=True)
assert len(raw) % 28 == 0
records = list(struct.iter_unpack("<I6f", raw))
assert all(row[0] in (1, 2, 3) for row in records)
xs = [row[i] for row in records for i in ((1, 3, 5) if row[0] == 3 else (5,))]
ys = [row[i] for row in records for i in ((2, 4, 6) if row[0] == 3 else (6,))]
left, top = min(xs), min(ys)
width, height = max(xs) - left, max(ys) - top
assert abs(width - 20) < .001 and abs(height - 12) < .001
commands, svg = [], []
for op, *values in records:
    if op == 1 and svg:
        svg.append("Z")
    indices = range(6) if op == 3 else range(4, 6)
    points = [values[i] - (left if i % 2 == 0 else top) for i in indices]
    svg.append({1: "M", 2: "L", 3: "C"}[op] + " ".join(f"{v:.6f}" for v in points))
    # Move and line use the endpoint; unused control points stay zero.
    normalized = points if op == 3 else [0.0] * 4 + points
    commands.append("    {" + str(op) + ", {" + ", ".join(f"{v:.6f}f" for v in normalized) + "}},")
svg.append("Z")
(source.parent / "battery-penpot.svg").write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 12">\n'
    '  <path fill="#76767d" fill-rule="evenodd" clip-rule="evenodd" d="'
    + " ".join(svg) + '"/>\n</svg>\n', encoding="utf-8")
(root / "native/include/sonyconnect/battery_icon.hpp").write_text(
    "// Generated by scripts/Generate-BatteryIcon.py from the supplied Penpot clipboard.\n"
    "#pragma once\n#include <array>\nnamespace sonyconnect::ui {\n"
    "struct BatteryPathCommand { unsigned operation; std::array<float, 6> points; };\n"
    f"inline constexpr std::array<BatteryPathCommand, {len(commands)}> battery_path{{{{\n"
    + "\n".join(commands) + "\n}};\n} // namespace sonyconnect::ui\n", encoding="utf-8")
print(f"Decoded {len(records)} path records: {width:g} x {height:g}, even-odd fill")
